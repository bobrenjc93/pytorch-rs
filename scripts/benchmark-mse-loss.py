def run(args):
    np, torch_rs, functional, reference_torch, reference_functional = import_benchmark_modules()
    if reference_torch.__version__.split("+")[0] != "2.13.0":
        raise SystemExit(
            "mse_loss benchmark differentials require pinned PyTorch 2.13.0, "
            f"got {reference_torch.__version__}"
        )

    results = []
    for workload in WORKLOADS:
        metadata = assert_correct(
            np,
            workload,
            (torch_rs, functional),
            (reference_torch, reference_functional),
        )
        actual = time_workload(np, torch_rs, functional, workload, args.warmups, args.samples)
        expected = time_workload(
            np,
            reference_torch,
            reference_functional,
            workload,
            args.warmups,
            args.samples,
        )
        ratio = actual["median"] / expected["median"]
        results.append(
            {
                "workload": workload,
                "shape": metadata["shape"],
                "stride": metadata["stride"],
                "actual": actual,
                "expected": expected,
                "ratio": ratio,
            }
        )

    report = render_report(
        np,
        torch_rs,
        reference_torch,
        results,
        args.warmups,
        args.samples,
    )
    if args.output is None:
        print(report)
    else:
        args.output.write_text(report, encoding="utf-8")
        print(f"wrote {args.output}")


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="write the generated Markdown report")
    parser.add_argument(
        "--check-report",
        type=Path,
        help="validate an existing Markdown benchmark report without timing",
    )
    parser.add_argument("--warmups", type=int, default=9)
    parser.add_argument("--samples", type=int, default=51)
    args = parser.parse_args()
    if args.warmups < 0 or args.samples <= 0:
        parser.error("--warmups must be non-negative and --samples must be positive")
    return args


def main() -> None:
    args = parse_args()
    if args.check_report is not None:
        check_report(args.check_report)
        print(f"validated {args.check_report}")
        return
    run(args)


if __name__ == "__main__":
    main()
