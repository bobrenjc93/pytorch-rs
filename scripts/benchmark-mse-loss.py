#!/usr/bin/env python3
"""Generate and validate the MSE loss timing report.

The primary metric intentionally materializes each eager output and consumes
every value through a checksum inside the timed loop. This keeps the benchmark
aligned with the repository policy that timed work must include the observable
tensor result, not only allocation or metadata creation.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import platform
import re
import statistics
import subprocess
import sys
import time
import warnings
from dataclasses import asdict, dataclass
from pathlib import Path


REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
SCRIPT_PATH = "scripts/benchmark-mse-loss.py"
CHECK_COMMAND = (
    "python scripts/benchmark-mse-loss.py "
    "--check-report docs/mse-loss-release-timings.md"
)
PRIMARY_SECTION = "## Primary: Materialized Checksum"
CHECKSUM_MASK = 0xFFFFFFFFFFFFFFFF
CHECKSUM_OFFSET = 0xCBF29CE484222325
CHECKSUM_PRIME = 0x100000001B3


@dataclass(frozen=True)
class Workload:
    name: str
    group: str
    builder: str
    input_target: str
    repeats: int


WORKLOADS = (
    Workload(
        "same_contiguous_prime_control",
        "control",
        "same_contiguous_prime",
        "`(257, 263)` / `(257, 263)`, contiguous",
        4,
    ),
    Workload(
        "same_contiguous_bandwidth_control",
        "control",
        "same_contiguous_bandwidth",
        "`(1536, 1536)` / `(1536, 1536)`, contiguous",
        1,
    ),
    Workload(
        "same_noncontiguous_transpose_control",
        "control",
        "same_noncontiguous_transpose",
        "transposed `(512, 1024)` / `(512, 1024)`, input stride `(1, 512)`",
        1,
    ),
    Workload(
        "scalar_input_contiguous_heldout_513x1021",
        "heldout",
        "scalar_input_513x1021",
        "`()` / `(513, 1021)`",
        1,
    ),
    Workload(
        "scalar_target_contiguous_heldout_513x1021",
        "heldout",
        "scalar_target_513x1021",
        "`(513, 1021)` / `()`",
        1,
    ),
    Workload(
        "scalar_input_contiguous_heldout_1537x257",
        "heldout",
        "scalar_input_1537x257",
        "`()` / `(1537, 257)`",
        1,
    ),
    Workload(
        "scalar_target_contiguous_heldout_1537x257",
        "heldout",
        "scalar_target_1537x257",
        "`(1537, 257)` / `()`",
        1,
    ),
    Workload(
        "scalar_input_empty_contiguous_heldout",
        "heldout",
        "scalar_input_empty",
        "`()` / `(17, 0, 19)`",
        2000,
    ),
    Workload(
        "scalar_target_empty_contiguous_heldout",
        "heldout",
        "scalar_target_empty",
        "`(17, 0, 19)` / `()`",
        2000,
    ),
)


def workload_digest() -> str:
    payload = json.dumps([asdict(workload) for workload in WORKLOADS], sort_keys=True)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


def check_report(path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    required_fragments = [
        f"Generated by: `{SCRIPT_PATH}`",
        f"Workload matrix digest: `{workload_digest()}`",
        PRIMARY_SECTION,
        CHECK_COMMAND,
        "full-output materialization",
        "value-consuming checksum",
    ]
    missing = [fragment for fragment in required_fragments if fragment not in text]
    for workload in WORKLOADS:
        pattern = (
            rf"^\| `{re.escape(workload.name)}` \| .* "
            r"\| `0x([0-9a-f]{16})` / `0x([0-9a-f]{16})` \|$"
        )
        match = re.search(pattern, text, flags=re.MULTILINE)
        if match is None:
            missing.append(f"checksum row for `{workload.name}`")
        elif match.group(1) != match.group(2):
            missing.append(f"matching checksums for `{workload.name}`")
    if "data-pointer/metadata sink" in text:
        missing.append("report still references the old data-pointer/metadata sink")
    if "## Eager Output Creation" in text:
        missing.append("old eager-output metric is still the report section")
    if missing:
        print("MSE benchmark report validation failed:", file=sys.stderr)
        for fragment in missing:
            print(f"- missing or invalid: {fragment}", file=sys.stderr)
        raise SystemExit(1)


def configure_thread_environment() -> None:
    for name in (
        "OMP_NUM_THREADS",
        "MKL_NUM_THREADS",
        "OPENBLAS_NUM_THREADS",
        "NUMEXPR_NUM_THREADS",
    ):
        os.environ.setdefault(name, "1")


def import_benchmark_modules():
    configure_thread_environment()
    import numpy as np
    import torch as reference_torch
    import torch_rs
    import torch_rs.nn.functional as functional
    import torch.nn.functional as reference_functional

    for module in (torch_rs, reference_torch):
        for setter in ("set_num_threads", "set_num_interop_threads"):
            if hasattr(module, setter):
                try:
                    getattr(module, setter)(1)
                except RuntimeError:
                    pass

    return np, torch_rs, functional, reference_torch, reference_functional


def tensor_from_array(module, array):
    return module.tensor(array.astype("float32").tolist(), dtype=module.float32)


def scalar_tensor(module, value: float):
    return module.tensor(float(value), dtype=module.float32)


def build_workload(np, module, builder: str):
    if builder == "same_contiguous_prime":
        values = np.linspace(-3.0, 5.0, 257 * 263, dtype=np.float32).reshape(
            257, 263
        )
        target = np.linspace(4.0, -2.0, 257 * 263, dtype=np.float32).reshape(
            257, 263
        )
        return tensor_from_array(module, values), tensor_from_array(module, target)

    if builder == "same_contiguous_bandwidth":
        values = np.linspace(-1.0, 1.0, 1536 * 1536, dtype=np.float32).reshape(
            1536, 1536
        )
        target = np.linspace(2.0, -2.0, 1536 * 1536, dtype=np.float32).reshape(
            1536, 1536
        )
        return tensor_from_array(module, values), tensor_from_array(module, target)

    if builder == "same_noncontiguous_transpose":
        values = np.linspace(-3.0, 3.0, 1024 * 512, dtype=np.float32).reshape(
            1024, 512
        )
        target = np.linspace(1.0, -4.0, 1024 * 512, dtype=np.float32).reshape(
            1024, 512
        )
        return (
            tensor_from_array(module, values).transpose(0, 1),
            tensor_from_array(module, target).transpose(0, 1),
        )

    if builder == "scalar_input_513x1021":
        target = np.linspace(-2.0, 3.0, 513 * 1021, dtype=np.float32).reshape(
            513, 1021
        )
        return scalar_tensor(module, -0.75), tensor_from_array(module, target)

    if builder == "scalar_target_513x1021":
        values = np.linspace(3.0, -2.0, 513 * 1021, dtype=np.float32).reshape(
            513, 1021
        )
        return tensor_from_array(module, values), scalar_tensor(module, 0.5)

    if builder == "scalar_input_1537x257":
        target = np.linspace(-4.0, 4.0, 1537 * 257, dtype=np.float32).reshape(
            1537, 257
        )
        return scalar_tensor(module, 1.25), tensor_from_array(module, target)

    if builder == "scalar_target_1537x257":
        values = np.linspace(4.0, -4.0, 1537 * 257, dtype=np.float32).reshape(
            1537, 257
        )
        return tensor_from_array(module, values), scalar_tensor(module, -1.5)

    if builder == "scalar_input_empty":
        return (
            scalar_tensor(module, -0.0),
            module.zeros((17, 0, 19), dtype=module.float32),
        )

    if builder == "scalar_target_empty":
        return (
            module.zeros((17, 0, 19), dtype=module.float32),
            scalar_tensor(module, -0.0),
        )

    raise ValueError(f"unknown MSE benchmark workload builder: {builder}")


def output_array(np, output):
    return np.asarray(output, dtype=np.float32).copy()


def checksum_output(np, output) -> int:
    array = output_array(np, output)
    bits = array.reshape(-1).view(np.uint32)
    checksum = 0x9E3779B97F4A7C15 ^ array.ndim
    for value in array.shape:
        checksum = ((checksum << 7) ^ (checksum >> 3) ^ int(value)) & CHECKSUM_MASK
    for value in output.stride():
        checksum = ((checksum << 7) ^ (checksum >> 3) ^ int(value)) & CHECKSUM_MASK
    if bits.size:
        checksum ^= int(np.bitwise_xor.reduce(bits, initial=np.uint32(0)))
        checksum = (checksum + int(bits.sum(dtype=np.uint64))) & CHECKSUM_MASK
    return checksum


def mix_checksum(checksum: int, value: int) -> int:
    return ((checksum ^ value) * CHECKSUM_PRIME) & CHECKSUM_MASK


def run_output(np, functional, input_tensor, target_tensor):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return functional.mse_loss(input_tensor, target_tensor, reduction="none")


def assert_correct(np, workload, actual_modules, reference_modules):
    actual_module, actual_functional = actual_modules
    reference_module, reference_functional = reference_modules
    actual_input, actual_target = build_workload(np, actual_module, workload.builder)
    expected_input, expected_target = build_workload(np, reference_module, workload.builder)
    actual = run_output(np, actual_functional, actual_input, actual_target)
    expected = run_output(np, reference_functional, expected_input, expected_target)

    if tuple(actual.shape) != tuple(expected.shape):
        raise AssertionError(
            f"{workload.name}: shape mismatch {tuple(actual.shape)} != {tuple(expected.shape)}"
        )
    if tuple(actual.stride()) != tuple(expected.stride()):
        raise AssertionError(
            f"{workload.name}: stride mismatch {actual.stride()} != {expected.stride()}"
        )

    actual_bits = output_array(np, actual).reshape(-1).view(np.uint32)
    expected_bits = output_array(np, expected).reshape(-1).view(np.uint32)
    if not np.array_equal(actual_bits, expected_bits):
        raise AssertionError(f"{workload.name}: bitwise output mismatch")

    return {
        "shape": tuple(int(value) for value in actual.shape),
        "stride": tuple(int(value) for value in actual.stride()),
    }


def run_block(np, functional, input_tensor, target_tensor, repeats: int) -> int:
    checksum = CHECKSUM_OFFSET
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        for index in range(repeats):
            output = functional.mse_loss(input_tensor, target_tensor, reduction="none")
            checksum = mix_checksum(checksum, checksum_output(np, output) ^ index)
    return checksum


def summarize(samples):
    median = statistics.median(samples)
    deviations = [abs(sample - median) for sample in samples]
    variance = statistics.variance(samples) if len(samples) > 1 else 0.0
    return {
        "median": median,
        "mad": statistics.median(deviations),
        "variance": variance,
    }


def time_workload(np, module, functional, workload, warmups: int, samples: int):
    input_tensor, target_tensor = build_workload(np, module, workload.builder)
    checksum = CHECKSUM_OFFSET
    for _ in range(warmups):
        checksum = mix_checksum(
            checksum,
            run_block(np, functional, input_tensor, target_tensor, workload.repeats),
        )

    timings = []
    for _ in range(samples):
        start = time.perf_counter_ns()
        checksum = mix_checksum(
            checksum,
            run_block(np, functional, input_tensor, target_tensor, workload.repeats),
        )
        elapsed = time.perf_counter_ns() - start
        timings.append(elapsed / workload.repeats / 1000.0)

    return {**summarize(timings), "checksum": checksum}


def geomean(values):
    return math.exp(sum(math.log(value) for value in values) / len(values))


def command_output(command):
    try:
        return subprocess.check_output(
            command,
            cwd=REPOSITORY_ROOT,
            stderr=subprocess.DEVNULL,
            text=True,
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unavailable"


def cpu_name():
    try:
        with open("/proc/cpuinfo", encoding="utf-8") as cpuinfo:
            for line in cpuinfo:
                if line.startswith("model name"):
                    return line.split(":", 1)[1].strip()
    except OSError:
        pass
    processor = platform.processor()
    if processor:
        return processor
    return "unavailable"


def repository_revision():
    revision = command_output(["git", "rev-parse", "--verify", "HEAD"])
    status = command_output(["git", "status", "--short"])
    if status and status != "unavailable":
        return f"{revision} with uncommitted tracked report/script updates"
    return revision


def format_us(stat):
    return (
        f"{stat['median']:.3f} us +/- {stat['mad']:.3f}, "
        f"var {stat['variance']:.3f}"
    )


